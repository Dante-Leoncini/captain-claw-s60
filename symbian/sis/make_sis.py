"""Builds the N95 installer: OpenClaw.pkg -> build_sis/OpenClaw.sisx, signed with a self-made SHA-1 certificate.

    python symbian/sis/make_sis.py            full package (exe + OpenClaw's own data, no CLAW.REZ)
    python symbian/sis/make_sis.py --quick    exe and resources only, as a partial upgrade (TYPE=PU)
    --run                                     start the game when the install finishes (for remote tests)

Everything goes to E: (the executable to E:\\sys\\bin, the data to E:\\data\\claw\\). The original game archive,
CLAW.REZ, is never packaged: copy it from the CD (\\DATA\\CLAW.REZ) to E:\\data\\claw\\ yourself.

The certificate (openclaw_sign.cer/.key next to this script) is created with openssl the first time and is not
versioned. It must be SHA-1: S60 3rd FP1 doesn't know SHA-256 and says the file is corrupted."""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SYMBIAN = os.path.normpath(os.path.join(HERE, '..'))
ROOT = os.path.normpath(os.path.join(SYMBIAN, '..'))
OUT = os.path.join(ROOT, 'build_sis')
CERT = os.path.join(HERE, 'openclaw_sign.cer')
KEY = os.path.join(HERE, 'openclaw_sign.key')
TOOLS = r'C:\epoc32\tools'
UID = '0xE0C1A75A'
EXE = r'\epoc32\release\armv5\urel\OpenClaw.exe'

sys.path.insert(0, os.path.join(SYMBIAN, 'tools'))
import make_assets  # noqa: E402

DATA = [
    (os.path.join(ROOT, 'build_sis', 'ASSETS.ZIP'), 'ASSETS.ZIP'),
    (os.path.join(SYMBIAN, 'data', 'claw', 'config.xml'), 'config.xml'),
    (os.path.join(ROOT, 'Build_Release', 'SAVES.XML'), 'SAVES.XML'),
]

HEADER = r''';
; OpenClaw (Captain Claw) for S60 3rd Edition. Generated by make_sis.py.
; CLAW.REZ from the original game goes to E:\data\claw\ by hand.
;
&EN

#{"Captain Claw"},(%(uid)s),0,1,0,TYPE=%(type)s

%%{"OpenClaw"}
:"OpenClaw"

[0x101F7961],0,0,0,{"Series60ProductID"}

"%(exe)s"                                                       -"E:\sys\bin\OpenClaw.exe"%(run)s
"\epoc32\data\z\resource\apps\OpenClaw.rsc"                     -"E:\resource\apps\OpenClaw.rsc"
"\epoc32\data\z\private\10003a3f\import\apps\OpenClaw_reg.rsc"  -"E:\private\10003a3f\import\apps\OpenClaw_reg.rsc"
"\epoc32\data\z\resource\apps\OpenClaw_icon.mif"                -"E:\resource\apps\OpenClaw_icon.mif"
'''


def certificate():
    if os.path.isfile(CERT) and os.path.isfile(KEY):
        return
    # (openssl 1.1+ writes PKCS#8; signsis wants the traditional RSA key)
    pkcs8 = KEY + '.pkcs8'
    subprocess.check_call(['openssl', 'req', '-x509', '-newkey', 'rsa:2048', '-sha1', '-days', '7300', '-nodes',
                           '-keyout', pkcs8, '-out', CERT, '-subj', '/CN=OpenClaw S60/O=OpenClaw'])
    # (openssl 3 needs -traditional for that; 1.1 doesn't know the flag and writes it by default)
    if subprocess.call(['openssl', 'rsa', '-traditional', '-in', pkcs8, '-out', KEY]) != 0:
        subprocess.check_call(['openssl', 'rsa', '-in', pkcs8, '-out', KEY])
    os.remove(pkcs8)
    print('new certificate:', CERT)


def check_imports(exe):
    """S60 3rd phones can't load an exe importing what only Symbian^3 exports ("feature not supported", or the
    install fails at the end when the package starts the game)."""
    out = subprocess.run([os.path.join(TOOLS, 'elftran.exe'), '-dump', 'i', exe], capture_output=True,
                         text=True).stdout
    dll = None
    for line in out.splitlines():
        if 'imports from' in line:
            dll = line.split('imports from')[1].strip().lower()
            if dll.startswith('scppnwdl'):
                raise SystemExit('%s imports scppnwdl.dll (missing on S60 3rd): see symbian/src/newdel.cpp' % exe)
        elif dll and dll.startswith('efsrv') and line.strip() == '390':
            raise SystemExit('%s imports efsrv@390 (RFs::Close, missing on S60 3rd): close the RFs as a '
                             'RSessionBase' % exe)


def build(quick=False, run=False):
    certificate()
    exe = 'C:' + EXE
    if not os.path.isfile(exe):
        raise SystemExit('missing %s: run symbian/build.bat first' % exe)
    check_imports(exe)
    lines = [HEADER % {'uid': UID, 'type': 'PU' if quick else 'SA', 'exe': EXE, 'run': ',FR,RI' if run else ''}]
    if not quick:
        make_assets.main([os.path.join(OUT, 'ASSETS.ZIP')])
        lines.append('\n; OpenClaw data (not the original CLAW.REZ)\n')
        for src, name in DATA:
            lines.append('"%s" -"E:\\data\\claw\\%s"\n' % (src, name))
    os.makedirs(OUT, exist_ok=True)
    name = 'OpenClaw_quick' if quick else 'OpenClaw'
    pkg = os.path.join(OUT, name + '.pkg')
    with open(pkg, 'w', newline='\r\n') as f:
        f.writelines(lines)
    sis = os.path.join(OUT, name + '.sis')
    sisx = os.path.join(OUT, name + '.sisx')
    for f in (sis, sisx):
        if os.path.exists(f):
            os.remove(f)
    # (makesis resolves \epoc32\... against the current drive)
    subprocess.check_call([os.path.join(TOOLS, 'makesis.exe'), pkg, sis], cwd='C:\\')
    subprocess.check_call([os.path.join(TOOLS, 'signsis.exe'), sis, sisx, CERT, KEY])
    os.remove(sis)
    print('%s: %.2f MB' % (sisx, os.path.getsize(sisx) / 1048576.0))
    return sisx


if __name__ == '__main__':
    build('--quick' in sys.argv, '--run' in sys.argv)
