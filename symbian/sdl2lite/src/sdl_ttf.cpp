enum { GLYPH_ROWS = 11, GLYPH_ADVANCE = 6 };

struct TTF_Font
{
    int scale;
};

int TTF_Init(void)
{
    return 0;
}

void TTF_Quit(void)
{
}

TTF_Font* TTF_OpenFont(const char*, int ptsize)
{
    TTF_Font* font = (TTF_Font*)malloc(sizeof(TTF_Font));
    if (font)
        font->scale = ptsize >= 28 ? 2 : 1;
    return font;
}

void TTF_CloseFont(TTF_Font* font)
{
    free(font);
}

int TTF_FontHeight(const TTF_Font* font)
{
    return font ? (GLYPH_ROWS + 2) * font->scale : 0;
}

int TTF_SizeText(TTF_Font* font, const char* text, int* w, int* h)
{
    if (!font || !text)
        return -1;
    if (w)
        *w = (int)strlen(text) * GLYPH_ADVANCE * font->scale;
    if (h)
        *h = TTF_FontHeight(font);
    return 0;
}

SDL_Surface* TTF_RenderText_Blended(TTF_Font* font, const char* text, SDL_Color fg)
{
    int w, h;
    if (TTF_SizeText(font, text, &w, &h) != 0)
        return NULL;
    if (w == 0)
        w = 1;
    SDL_Surface* s = SDL_CreateRGBSurface(0, w, h, 32, 0, 0, 0, 0);
    if (!s)
        return NULL;
    const Uint32 color = SDL_MapRGBA(s->format, fg.r, fg.g, fg.b, 255);
    const int scale = font->scale;
    Uint32* px = (Uint32*)s->pixels;
    for (int i = 0; text[i]; i++)
    {
        const unsigned char c = (unsigned char)text[i];
        if (c < 32 || c > 126)
            continue;
        const unsigned char* glyph = kFontGlyphs[c - 32];
        for (int row = 0; row < GLYPH_ROWS; row++)
        {
            for (int bit = 0; bit < 8; bit++)
            {
                if (!(glyph[row] & (0x80 >> bit)))
                    continue;
                for (int sy = 0; sy < scale; sy++)
                {
                    const int y = (row + 1) * scale + sy;
                    for (int sx = 0; sx < scale; sx++)
                    {
                        const int x = (i * GLYPH_ADVANCE + bit) * scale + sx;
                        if (x < w && y < h)
                            px[y * w + x] = color;
                    }
                }
            }
        }
    }
    return s;
}

SDL_Surface* TTF_RenderText_Solid(TTF_Font* font, const char* text, SDL_Color fg)
{
    return TTF_RenderText_Blended(font, text, fg);
}
