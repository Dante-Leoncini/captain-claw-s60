"""Writes symbian/group/game_sources.mmh and libwap_sources.mmh (SOURCEPATH/SOURCE lines)."""
import collections
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SKIP = {'OpenClaw/Engine/Resource/Miniz.cpp'}  # same code as libwap/Miniz.cpp


def collect(bases):
    srcs = []
    for base in bases:
        for dp, dn, fn in os.walk(os.path.join(ROOT, base)):
            dn.sort()
            for f in sorted(fn):
                if f.endswith('.cpp'):
                    rel = os.path.relpath(os.path.join(dp, f), ROOT).replace(os.sep, '/')
                    if rel not in SKIP:
                        srcs.append(rel)
    return srcs


def write(name, srcs):
    groups = collections.OrderedDict()
    for p in srcs:
        d, f = p.rsplit('/', 1)
        groups.setdefault(d, []).append(f)
    lines = ['// Generated by symbian/tools/gen_sources.py']
    for d, files in groups.items():
        lines.append('SOURCEPATH      ..\\..\\' + d.replace('/', '\\'))
        line = 'SOURCE         '
        for f in files:
            if len(line) + len(f) > 110:
                lines.append(line)
                line = 'SOURCE         '
            line += ' ' + f
        lines.append(line)
    out = os.path.join(ROOT, 'symbian', 'group', name)
    with open(out, 'w', newline='\r\n') as fp:
        fp.write('\n'.join(lines) + '\n')
    print('%d sources -> %s' % (sum(len(v) for v in groups.values()), out))


def main():
    tinyxml = ['ThirdParty/Tinyxml/' + f for f in ('tinyxml.cpp', 'tinystr.cpp', 'tinyxmlerror.cpp', 'tinyxmlparser.cpp')]
    write('game_sources.mmh', collect(('OpenClaw', 'Box2D/Box2D')) + tinyxml + ['ThirdParty/libsmacker/smacker.c'])
    write('libwap_sources.mmh', collect(('libwap',)))


if __name__ == '__main__':
    main()
